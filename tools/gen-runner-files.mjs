// Regenerate src/runner-files.generated.ts from ../runner/.
// The plugin ships these files to each new runner (runner conversion, T6);
// test/conversion.test.ts fails if the embedded copy drifts from the repo copy.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const src = join(here, "..", "runner");
const files = { RUNNER_ENSURE_SH: "runner-ensure.sh", BB_RUNNER_GUARD_SH: "bb-runner-guard.sh" };
let out = "// GENERATED by tools/gen-runner-files.mjs from runner/. Do not edit.\n";
for (const [name, file] of Object.entries(files)) {
  const lines = readFileSync(join(src, file), "utf8").split("\n");
  out += `\nexport const ${name} = [\n${lines.map((l) => `  ${JSON.stringify(l)},`).join("\n")}\n].join("\\n");\n`;
}
writeFileSync(join(here, "..", "src", "runner-files.generated.ts"), out);
console.log("wrote src/runner-files.generated.ts");
